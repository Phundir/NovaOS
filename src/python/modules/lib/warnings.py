"""warnings for Nova's Python: issue, filter, record and show warnings.

The pure Python implementation of CPython 3.13 (PSF License): a list of
filters (action, message regex, category, module regex, line number)
searched front to back for each warning, per-module registries that
make the "default", "module" and "once" actions print a warning only
once, catch_warnings to save and restore that state (and record=True to
collect WarningMessage objects instead of printing them), and the output
format `file:line: Category: message` followed by the source line, on
stderr. The default filters are CPython's: DeprecationWarning is shown
only when raised from __main__; PendingDeprecationWarning, ImportWarning
and ResourceWarning are ignored.

Nova's Python only has `Warning` among the built-in warning classes, so
this module defines the others (UserWarning, DeprecationWarning, ...)
with CPython's hierarchy and installs them into builtins: once warnings
is imported, `UserWarning` and its siblings are plain names everywhere.

Limit: Nova's Python does not expose call frames (sys._getframe always
raises ValueError), so warn() cannot know which line called it. It then
attributes the warning to the main script: module '__main__', file
sys.argv[0], line 0, and no source line is printed. warn_explicit() and
showwarning() with an explicit file and line behave exactly as in
CPython. As soon as sys._getframe works, warn() follows CPython's path
(stacklevel, skip_file_prefixes) unchanged.
"""

import sys
import builtins as _builtins

__all__ = ["warn", "warn_explicit", "showwarning",
           "formatwarning", "filterwarnings", "simplefilter",
           "resetwarnings", "catch_warnings", "deprecated"]


def _install_categories():
    """Create the built-in warning categories Nova's Python lacks."""
    names = ('UserWarning', 'DeprecationWarning', 'PendingDeprecationWarning',
             'SyntaxWarning', 'RuntimeWarning', 'FutureWarning',
             'ImportWarning', 'UnicodeWarning', 'BytesWarning',
             'ResourceWarning', 'EncodingWarning')
    docs = {
        'UserWarning': 'Base class for warnings generated by user code.',
        'DeprecationWarning': 'Base class for warnings about deprecated features.',
        'PendingDeprecationWarning': 'Base class for warnings about features which '
                                     'will be deprecated in the future.',
        'SyntaxWarning': 'Base class for warnings about dubious syntax.',
        'RuntimeWarning': 'Base class for warnings about dubious runtime behavior.',
        'FutureWarning': 'Base class for warnings about constructs that will '
                         'change semantically in the future.',
        'ImportWarning': 'Base class for warnings about probable mistakes in '
                         'module imports',
        'UnicodeWarning': 'Base class for warnings about Unicode related problems, '
                          'mostly related to conversion problems.',
        'BytesWarning': 'Base class for warnings about bytes and buffer related '
                        'problems, mostly related to conversion from str or '
                        'comparing to str.',
        'ResourceWarning': 'Base class for warnings about resource usage.',
        'EncodingWarning': 'Base class for warnings about encodings.',
    }
    for name in names:
        if not hasattr(_builtins, name):
            cls = type(name, (Warning,), {'__module__': 'builtins',
                                          '__doc__': docs[name]})
            setattr(_builtins, name, cls)


_install_categories()
del _install_categories

UserWarning = _builtins.UserWarning
DeprecationWarning = _builtins.DeprecationWarning
PendingDeprecationWarning = _builtins.PendingDeprecationWarning
RuntimeWarning = _builtins.RuntimeWarning
ImportWarning = _builtins.ImportWarning
ResourceWarning = _builtins.ResourceWarning


def _getline(filename, lineno):
    """Line `lineno` of file `filename` ('' when it cannot be read);
    stands in for linecache.getline."""
    if lineno < 1 or not filename or filename[0] == '<':
        return ''
    try:
        with open(filename) as f:
            for i, line in enumerate(f, 1):
                if i == lineno:
                    return line
    except Exception:
        pass
    return ''


def showwarning(message, category, filename, lineno, file=None, line=None):
    """Hook to write a warning to a file; replace if you like."""
    msg = WarningMessage(message, category, filename, lineno, file, line)
    _showwarnmsg_impl(msg)


def formatwarning(message, category, filename, lineno, line=None):
    """Function to format a warning the standard way."""
    msg = WarningMessage(message, category, filename, lineno, None, line)
    return _formatwarnmsg_impl(msg)


def _showwarnmsg_impl(msg):
    file = msg.file
    if file is None:
        file = sys.stderr
        if file is None:
            return
    text = _formatwarnmsg(msg)
    try:
        file.write(text)
    except OSError:
        pass


def _formatwarnmsg_impl(msg):
    category = msg.category.__name__
    s = f"{msg.filename}:{msg.lineno}: {category}: {msg.message}\n"
    if msg.line is None:
        try:
            line = _getline(msg.filename, msg.lineno)
        except Exception:
            line = None
    else:
        line = msg.line
    if line:
        line = line.strip()
        s += "  %s\n" % line
    return s


# Keep a reference to check if the function was replaced
_showwarning_orig = showwarning


def _showwarnmsg(msg):
    """Call showwarning() if it was replaced, the default writer otherwise."""
    sw = showwarning
    if sw is not _showwarning_orig:
        if not callable(sw):
            raise TypeError("warnings.showwarning() must be set to a "
                            "function or method")
        sw(msg.message, msg.category, msg.filename, msg.lineno,
           msg.file, msg.line)
        return
    _showwarnmsg_impl(msg)


# Keep a reference to check if the function was replaced
_formatwarning_orig = formatwarning


def _formatwarnmsg(msg):
    fw = formatwarning
    if fw is not _formatwarning_orig:
        return fw(msg.message, msg.category,
                  msg.filename, msg.lineno, msg.line)
    return _formatwarnmsg_impl(msg)


_ACTIONS = {"error", "ignore", "always", "default", "module", "once"}


def filterwarnings(action, message="", category=Warning, module="", lineno=0,
                   append=False):
    """Insert an entry into the list of warnings filters (at the front).

    'action' -- one of "error", "ignore", "always", "default", "module",
                or "once"
    'message' -- a regex that the warning message must match
    'category' -- a class that the warning must be a subclass of
    'module' -- a regex that the module name must match
    'lineno' -- an integer line number, 0 matches all warnings
    'append' -- if true, append to the list of filters
    """
    if action not in _ACTIONS:
        raise ValueError(f"invalid action: {action!r}")
    if not isinstance(message, str):
        raise TypeError("message must be a string")
    if not isinstance(category, type) or not issubclass(category, Warning):
        raise TypeError("category must be a Warning subclass")
    if not isinstance(module, str):
        raise TypeError("module must be a string")
    if not isinstance(lineno, int):
        raise TypeError("lineno must be an int")
    if lineno < 0:
        raise ValueError("lineno must be an int >= 0")

    if message or module:
        import re
    if message:
        message = re.compile(message, re.I)
    else:
        message = None
    if module:
        module = re.compile(module)
    else:
        module = None

    _add_filter(action, message, category, module, lineno, append=append)


def simplefilter(action, category=Warning, lineno=0, append=False):
    """Insert a simple entry into the list of warnings filters (at the front).

    A simple filter matches all modules and messages.
    """
    if action not in _ACTIONS:
        raise ValueError(f"invalid action: {action!r}")
    if not isinstance(lineno, int):
        raise TypeError("lineno must be an int")
    if lineno < 0:
        raise ValueError("lineno must be an int >= 0")
    _add_filter(action, None, category, None, lineno, append=append)


def _add_filter(*item, append):
    # Remove a duplicate so that the new filter lands at the right place;
    # with append=True an existing duplicate is left alone.
    if not append:
        try:
            filters.remove(item)
        except ValueError:
            pass
        filters.insert(0, item)
    else:
        if item not in filters:
            filters.append(item)
    _filters_mutated()


def resetwarnings():
    """Clear the list of warning filters, so that no filters are active."""
    filters[:] = []
    _filters_mutated()


class _OptionError(Exception):
    """Exception used by option processing helpers."""
    pass


def _processoptions(args):
    for arg in args:
        try:
            _setoption(arg)
        except _OptionError as msg:
            print("Invalid -W option ignored:", msg, file=sys.stderr)


def _setoption(arg):
    parts = arg.split(':')
    if len(parts) > 5:
        raise _OptionError("too many fields (max 5): %r" % (arg,))
    while len(parts) < 5:
        parts.append('')
    action, message, category, module, lineno = [s.strip() for s in parts]
    action = _getaction(action)
    category = _getcategory(category)
    if message or module:
        import re
    if message:
        message = re.escape(message)
    if module:
        module = re.escape(module) + r'\Z'
    if lineno:
        try:
            lineno = int(lineno)
            if lineno < 0:
                raise ValueError
        except (ValueError, OverflowError):
            raise _OptionError("invalid lineno %r" % (lineno,)) from None
    else:
        lineno = 0
    filterwarnings(action, message, category, module, lineno)


def _getaction(action):
    if not action:
        return "default"
    if action == "all":
        return "always"
    for a in ('default', 'always', 'ignore', 'module', 'once', 'error'):
        if a.startswith(action):
            return a
    raise _OptionError("invalid action: %r" % (action,))


def _getcategory(category):
    if not category:
        return Warning
    if '.' not in category:
        m = _builtins
        klass = category
    else:
        module, _, klass = category.rpartition('.')
        try:
            m = __import__(module, None, None, [klass])
        except ImportError:
            raise _OptionError("invalid module name: %r" % (module,)) from None
    try:
        cat = getattr(m, klass)
    except AttributeError:
        raise _OptionError("unknown warning category: %r" % (category,)) from None
    if not issubclass(cat, Warning):
        raise _OptionError("invalid warning category: %r" % (category,))
    return cat


def _is_internal_filename(filename):
    return 'importlib' in filename and '_bootstrap' in filename


def _is_filename_to_skip(filename, skip_file_prefixes):
    return any(filename.startswith(prefix) for prefix in skip_file_prefixes)


def _is_internal_frame(frame):
    return _is_internal_filename(frame.f_code.co_filename)


def _next_external_frame(frame, skip_file_prefixes):
    """Find the next frame that doesn't involve Python or user internals."""
    frame = frame.f_back
    while frame is not None:
        filename = frame.f_code.co_filename
        if not (_is_internal_filename(filename) or
                _is_filename_to_skip(filename, skip_file_prefixes)):
            break
        frame = frame.f_back
    return frame


# Registries used when no frame is available (see the module docstring),
# one per module name, as CPython keeps one in each module's globals.
_fallback_registries = {}


def _caller_context(stacklevel, skip_file_prefixes):
    """Return (globals or None, filename, lineno, module) for warn()."""
    try:
        if stacklevel <= 1 or _is_internal_frame(sys._getframe(2)):
            frame = sys._getframe(stacklevel + 1)
        else:
            frame = sys._getframe(2)
            for x in range(stacklevel - 1):
                frame = _next_external_frame(frame, skip_file_prefixes)
                if frame is None:
                    raise ValueError
    except ValueError:
        argv = getattr(sys, 'argv', None)
        filename = argv[0] if argv and argv[0] else "<sys>"
        return None, filename, 0, "__main__"
    globals = frame.f_globals
    module = globals['__name__'] if '__name__' in globals else "<string>"
    return globals, frame.f_code.co_filename, frame.f_lineno, module


def warn(message, category=None, stacklevel=1, source=None,
         *, skip_file_prefixes=()):
    """Issue a warning, or maybe ignore it or raise an exception."""
    if isinstance(message, Warning):
        category = message.__class__
    if category is None:
        category = UserWarning
    if not (isinstance(category, type) and issubclass(category, Warning)):
        raise TypeError("category must be a Warning subclass, "
                        "not '{:s}'".format(type(category).__name__))
    if not isinstance(skip_file_prefixes, tuple):
        raise TypeError('skip_file_prefixes must be a tuple of strs.')
    if skip_file_prefixes:
        stacklevel = max(2, stacklevel)
    globals, filename, lineno, module = _caller_context(stacklevel,
                                                        skip_file_prefixes)
    if globals is None:
        registry = _fallback_registries.setdefault(module, {})
    else:
        registry = globals.setdefault("__warningregistry__", {})
    warn_explicit(message, category, filename, lineno, module, registry,
                  globals, source)


def warn_explicit(message, category, filename, lineno,
                  module=None, registry=None, module_globals=None,
                  source=None):
    """Issue a warning attributed to an explicit file, line and module."""
    lineno = int(lineno)
    if module is None:
        module = filename or "<unknown>"
        if module[-3:].lower() == ".py":
            module = module[:-3]
    if registry is None:
        registry = {}
    if registry.get('version', 0) != _filters_version:
        registry.clear()
        registry['version'] = _filters_version
    if isinstance(message, Warning):
        text = str(message)
        category = message.__class__
    else:
        text = message
        message = category(message)
    key = (text, category, lineno)
    # Quick test for common case
    if registry.get(key):
        return
    # Search the filters
    for item in filters:
        action, msg, cat, mod, ln = item
        if ((msg is None or msg.match(text)) and
                issubclass(category, cat) and
                (mod is None or mod.match(module)) and
                (ln == 0 or lineno == ln)):
            break
    else:
        action = defaultaction
    if action == "ignore":
        return
    if action == "error":
        raise message
    if action == "once":
        registry[key] = 1
        oncekey = (text, category)
        if onceregistry.get(oncekey):
            return
        onceregistry[oncekey] = 1
    elif action == "always":
        pass
    elif action == "module":
        registry[key] = 1
        altkey = (text, category, 0)
        if registry.get(altkey):
            return
        registry[altkey] = 1
    elif action == "default":
        registry[key] = 1
    else:
        raise RuntimeError(
            "Unrecognized action (%r) in warnings.filters:\n %s" %
            (action, item))
    msg = WarningMessage(message, category, filename, lineno, source=source)
    _showwarnmsg(msg)


class WarningMessage(object):

    _WARNING_DETAILS = ("message", "category", "filename", "lineno", "file",
                        "line", "source")

    def __init__(self, message, category, filename, lineno, file=None,
                 line=None, source=None):
        self.message = message
        self.category = category
        self.filename = filename
        self.lineno = lineno
        self.file = file
        self.line = line
        self.source = source
        self._category_name = category.__name__ if category else None

    def __str__(self):
        return ("{message : %r, category : %r, filename : %r, lineno : %s, "
                "line : %r}" % (self.message, self._category_name,
                                self.filename, self.lineno, self.line))


def _this_module():
    """This module object. Nova's sys.modules is a snapshot taken when
    sys is first imported, so it may not list warnings: importing the
    module again returns it from the interpreter's own registry."""
    try:
        return sys.modules['warnings']
    except KeyError:
        return __import__(__name__)


class catch_warnings(object):
    """A context manager that copies and restores the warnings filter upon
    exiting the context.

    With record=True, warnings are not shown but appended, as
    WarningMessage objects, to the list returned by __enter__. If
    'action' is given, simplefilter(action, category, lineno, append)
    is applied on entering.
    """

    def __init__(self, *, record=False, module=None,
                 action=None, category=Warning, lineno=0, append=False):
        self._record = record
        self._module = _this_module() if module is None else module
        self._entered = False
        if action is None:
            self._filter = None
        else:
            self._filter = (action, category, lineno, append)

    def __repr__(self):
        args = []
        if self._record:
            args.append("record=True")
        if self._module is not _this_module():
            args.append("module=%r" % self._module)
        name = type(self).__name__
        return "%s(%s)" % (name, ", ".join(args))

    def __enter__(self):
        if self._entered:
            raise RuntimeError("Cannot enter %r twice" % self)
        self._entered = True
        self._filters = self._module.filters
        self._module.filters = self._filters[:]
        self._module._filters_mutated()
        self._showwarning = self._module.showwarning
        self._showwarnmsg_impl = self._module._showwarnmsg_impl
        if self._filter is not None:
            self._module.simplefilter(*self._filter)
        if self._record:
            log = []
            self._module._showwarnmsg_impl = log.append
            # Reset showwarning() to the default implementation so that
            # _showwarnmsg() calls _showwarnmsg_impl().
            self._module.showwarning = self._module._showwarning_orig
            return log
        else:
            return None

    def __exit__(self, *exc_info):
        if not self._entered:
            raise RuntimeError("Cannot exit %r without entering first" % self)
        self._module.filters = self._filters
        self._module._filters_mutated()
        self._module.showwarning = self._showwarning
        self._module._showwarnmsg_impl = self._showwarnmsg_impl


class deprecated:
    """Decorator (PEP 702) marking a class or function as deprecated:
    using it emits `category` (DeprecationWarning by default) with
    `message`, which is also stored in __deprecated__."""

    def __init__(self, message, /, *, category=DeprecationWarning,
                 stacklevel=1):
        if not isinstance(message, str):
            raise TypeError(
                f"Expected an object of type str for 'message', not {type(message).__name__!r}"
            )
        self.message = message
        self.category = category
        self.stacklevel = stacklevel

    def __call__(self, arg, /):
        msg = self.message
        category = self.category
        stacklevel = self.stacklevel
        if category is None:
            arg.__deprecated__ = msg
            return arg
        elif isinstance(arg, type):
            import functools
            original_new = arg.__new__

            def __new__(cls, /, *args, **kwargs):
                if cls is arg:
                    warn(msg, category=category, stacklevel=stacklevel + 1)
                if original_new is not object.__new__:
                    return original_new(cls, *args, **kwargs)
                elif cls.__init__ is object.__init__ and (args or kwargs):
                    raise TypeError(f"{cls.__name__}() takes no arguments")
                else:
                    return original_new(cls)

            arg.__new__ = staticmethod(__new__)

            def __init_subclass__(cls, *args, **kwargs):
                warn(msg, category=category, stacklevel=stacklevel + 1)
                return super(arg, cls).__init_subclass__(*args, **kwargs)

            arg.__init_subclass__ = classmethod(__init_subclass__)
            arg.__deprecated__ = __new__.__deprecated__ = msg
            __init_subclass__.__deprecated__ = msg
            return arg
        elif callable(arg):
            import functools

            @functools.wraps(arg)
            def wrapper(*args, **kwargs):
                warn(msg, category=category, stacklevel=stacklevel + 1)
                return arg(*args, **kwargs)

            arg.__deprecated__ = wrapper.__deprecated__ = msg
            return wrapper
        else:
            raise TypeError(
                "@deprecated decorator with non-None category must be applied to "
                f"a class or callable, not {arg!r}"
            )


_DEPRECATED_MSG = "{name!r} is deprecated and slated for removal in Python {remove}"


def _deprecated(name, message=_DEPRECATED_MSG, *, remove, _version=sys.version_info):
    """Warn that *name* is deprecated or should be removed."""
    remove_formatted = f"{remove[0]}.{remove[1]}"
    if (_version[:2] > remove) or (_version[:2] == remove and _version[3] != "alpha"):
        msg = f"{name!r} was slated for removal after Python {remove_formatted} alpha"
        raise RuntimeError(msg)
    else:
        msg = message.format(name=name, remove=remove_formatted)
        warn(msg, DeprecationWarning, stacklevel=3)


# filters holds 5-tuples (action, message regex or None, category,
# module regex or None, lineno or 0); None regexes match anything.
filters = []
defaultaction = "default"
onceregistry = {}
_filters_version = 1


def _filters_mutated():
    global _filters_version
    _filters_version += 1


_processoptions(getattr(sys, 'warnoptions', []))
filterwarnings("default", category=DeprecationWarning,
               module="__main__", append=1)
simplefilter("ignore", category=DeprecationWarning, append=1)
simplefilter("ignore", category=PendingDeprecationWarning, append=1)
simplefilter("ignore", category=ImportWarning, append=1)
simplefilter("ignore", category=ResourceWarning, append=1)
