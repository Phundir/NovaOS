BOX_X, BOX_Y = 1, 4

def encode(rows):
    cell = [0] * 16
    for r, line in enumerate(rows):
        byte = 0
        for c, px in enumerate(line):
            if px == '#':
                byte |= 1 << (7 - (BOX_X + c))
        cell[BOX_Y + r] = byte
    return cell

first, last = 0x20, 0x7E
missing = [c for c in range(first, last + 1) if chr(c) not in G]
assert not missing, ['0x%02x' % c for c in missing]

out = []
out.append('''//! 8x16 bitmap font of the graphics driver.
//!
//! ## Why a font written here
//!
//! The kernel admits no external dependency, and a console font borrowed
//! from the host would additionally raise a licensing question in a
//! redistributed binary. So the glyphs are drawn for Nova OS, in a box of
//! 5 columns by 9 rows laid at offset (1, 4) of the 8x16 cell: one empty
//! column on the left, two on the right and four rows above give the
//! letter spacing and the line spacing without the renderer having to add
//! them.
//!
//! Rows 0 to 6 of the box carry the body, row 6 is the baseline; rows 7
//! and 8 receive the descenders of `g j p q y` and of the comma.
//!
//! ## Representation
//!
//! A glyph is an array of sixteen bytes, one per row of the cell. Bit 7 is
//! the leftmost pixel. That choice makes rendering a row a plain left
//! shift, with no indirection table.
//!
//! The file is produced by a generator from an ASCII-art description;
//! editing it by hand is possible, but the art is easier to read back than
//! a run of bytes.

/// Dimensions of a character cell, in pixels.
pub const GLYPH_WIDTH: usize = 8;
pub const GLYPH_HEIGHT: usize = 16;

/// First and last code point covered.
pub const FIRST: u8 = 0x20;
pub const LAST: u8 = 0x7E;

/// Glyph rendered in place of any byte outside the printable range --
/// same convention as the VGA writer, which substitutes a solid square.
pub const REPLACEMENT: [u8; GLYPH_HEIGHT] = [
    0x00, 0x00, 0x00, 0x00, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x7C, 0x00, 0x00, 0x00, 0x00, 0x00,
];

/// Returns the glyph of a byte, or the solid square if it is out of range.
pub fn glyph(byte: u8) -> &'static [u8; GLYPH_HEIGHT] {
    if byte < FIRST || byte > LAST {
        return &REPLACEMENT;
    }
    &GLYPHS[(byte - FIRST) as usize]
}

/// One glyph per code point from 0x20 to 0x7E inclusive.
static GLYPHS: [[u8; GLYPH_HEIGHT]; (LAST - FIRST + 1) as usize] = [''')

names = {0x20: 'space', 0x27: "apostrophe", 0x22: 'quote', 0x5C: 'backslash'}
for code in range(first, last + 1):
    ch = chr(code)
    cell = encode(G[ch])
    label = names.get(code, ch)
    body = ', '.join('0x%02X' % b for b in cell)
    out.append('    // 0x%02X  %s' % (code, label))
    out.append('    [%s],' % body)
out.append('];')
out.append('')

open('src/graphics/font.rs', 'w', encoding='utf-8').write('\n'.join(out))
print('generated: %d glyphs' % (last - first + 1))
