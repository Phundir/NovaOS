#!/bin/sh
# Run by Nova at the end of its self-tests when present in the root image
# (linux::autostart).
#
# With the Web Browser fork and the Nova display device, the browser opens
# in a Nova window and this script waits for it. Otherwise (Alpine's
# firefox-esr only) it renders a test page without a screen and prints the
# screenshot base64-encoded on the serial console, between two markers,
# for tools/ports/extract-shot.sh on the host.
export HOME=/home/nova
export MOZ_HEADLESS=1
export MOZ_CRASHREPORTER_DISABLE=1
export MOZ_DISABLE_CONTENT_SANDBOX=1 MOZ_DISABLE_GMP_SANDBOX=1 MOZ_DISABLE_RDD_SANDBOX=1
export MOZ_DISABLE_SOCKET_PROCESS_SANDBOX=1 MOZ_DISABLE_UTILITY_SANDBOX=1
mkdir -p /home/nova /tmp/prof
cp /nova/user.js /tmp/prof/user.js
cat > /tmp/page.html <<'PAGE'
<html><body style="background:#eef;font-family:sans-serif">
<h1>Nova OS</h1><p>Page rendue par Gecko sur Nova OS.</p>
<p id="js">JavaScript inactif</p>
<script>document.getElementById("js").textContent = "JavaScript actif : " + (6 * 7);</script>
</body></html>
PAGE

if [ -x /usr/lib/web-browser/web-browser ]; then
    # The browser is opened from the Nova menu. Only a test image
    # (NOVA_AUTOSTART_BROWSER=1 tools/ports/webroot.sh) opens it at login.
    [ -e /nova/open-browser-at-login ] || exit 0
fi
# The clock Linux programs see: the zone of the session (/etc/localtime,
# generated by Nova) and the time set by the network synchronisation.
echo "autostart: heure locale $(date '+%Y-%m-%d %H:%M:%S %Z') - fuseau $(readlink /etc/localtime)"
if [ -x /usr/lib/web-browser/web-browser ] && [ -e /dev/nova-gui ]; then
    echo "autostart: Web Browser dans une fenetre Nova"
    /usr/bin/web-browser-nova
    echo "autostart: navigateur termine, code $?"
    exit 0
fi

BROWSER=$(ls /usr/lib/firefox-esr/firefox-esr 2>/dev/null | head -1)
echo "autostart: $BROWSER (capture sans ecran)"
"$BROWSER" --headless --no-remote --profile /tmp/prof --screenshot /tmp/shot.png file:///tmp/page.html
echo "autostart: navigateur termine, code $?"
if [ -f /tmp/shot.png ]; then
    echo "=== NOVA-SHOT-BEGIN ==="
    base64 /tmp/shot.png
    echo "=== NOVA-SHOT-END ==="
fi
