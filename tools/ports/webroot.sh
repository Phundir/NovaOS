#!/bin/sh
# Builds build/ports/webroot, the root of Nova's Linux subsystem (phase
# 11.6): Alpine packages, the test programs of tools/ports/tests, the Web
# Browser fork and its prepared profile. The tree is then written into
# the Nova volume by tools/nova-fs.py (`make webroot` does both): the
# browser's files are nodes of the filesystem like any others, and there
# is no second disk and no second filesystem any more.
#
# Usage: tools/ports/webroot.sh [package...]
# The packages default to the base set; the browser adds its own.
set -e
REPO="$(cd "$(dirname "$0")/../.." && pwd)"
STAGE="$REPO/build/ports/webroot"
PACKAGES="${*:-alpine-baselayout alpine-release musl}"

rm -rf "$STAGE"
mkdir -p "$REPO/build/ports/media"
mkdir -p "$STAGE/nova-tests"

# The SPIR-V of the GPU test program (phase 13.7.1), as a C header: the
# shaders the kernel's own self-test draws with (src/gpu/shaders).
python3 - "$REPO" <<'PYTHON'
import pathlib, sys
repo = pathlib.Path(sys.argv[1])
out = ['/* Generated by tools/ports/webroot.sh from the SPIR-V of src/gpu/shaders. */']
for name in ['triangle.vert', 'triangle.frag', 'busy.vert', 'busy.frag']:
    data = (repo / 'src/gpu/shaders' / (name + '.spv')).read_bytes()
    ident = name.replace('.', '_') + '_spv'
    out.append('static const unsigned char %s[%d] __attribute__((aligned(4))) = {' % (ident, len(data)))
    for i in range(0, len(data), 16):
        out.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',')
    out.append('};')
(repo / 'build/ports/gpu_shaders.h').write_text('\n'.join(out) + '\n')
PYTHON

"$REPO/tools/ports/alpine.sh" "
set -e
# apk returns 2 in this root: two setuid owners a fake root cannot keep
# (dbus, pam). The packages are installed; what matters is checked below.
apk add --quiet gcc musl-dev alsa-lib-dev sqlite-dev rust cargo >/dev/null 2>&1 || true
command -v gcc >/dev/null
cd /nova/tools/ports/tests
for t in hello threads memory files events signals spawn mmstress sysbench; do
    gcc -static -O2 -pthread -o /nova/build/ports/webroot/nova-tests/\$t \$t.c
done
gcc -O2 -o /nova/build/ports/webroot/nova-tests/dynamic dynamic.c
# Phase 12: the same programs linked dynamically, for the Nova interface:
# at run time their C library is the Nova one (/sys/runtimes/c/libc.so),
# not the one they were linked against.
mkdir -p /nova/build/ports/webroot/nova-tests/natif
for t in hello threads memory files events signals mmstress sysbench; do
    gcc -O2 -pthread -o /nova/build/ports/webroot/nova-tests/natif/\$t \$t.c
done
gcc -O2 -pthread -DHELLO_PATH='\"/nova-tests/natif/hello\"' -o /nova/build/ports/webroot/nova-tests/natif/spawn spawn.c
gcc -O2 -o /nova/build/ports/webroot/nova-tests/natif/database database.c -lsqlite3
# Phase 13: the GPU through nova_gfx.h, nothing else.
gcc -O2 -Wall -I/nova/tools/ports/nova-gfx -I/nova/build/ports -o /nova/build/ports/webroot/nova-tests/natif/gpu gpu.c
# Phase 13.6.3: the same from Rust, through the nova-gfx crate. Built in a
# copy of its tree outside the repository: cargo would otherwise take the
# kernel's .cargo/config.toml (its target, build-std) for its own.
rm -rf /tmp/gfx && mkdir -p /tmp/gfx/tools/ports/tests /tmp/gfx/src/gpu
cp -r /nova/tools/ports/nova-gfx /tmp/gfx/tools/ports/
cp -r /nova/tools/ports/tests/gpu-rust /tmp/gfx/tools/ports/tests/
cp -r /nova/src/gpu/shaders /tmp/gfx/src/gpu/
(cd /tmp/gfx/tools/ports/tests/gpu-rust && CARGO_TARGET_DIR=/nova/build/ports/gpu-rust cargo build --release --offline --quiet)
cp /nova/build/ports/gpu-rust/release/gpu-rust /nova/build/ports/webroot/nova-tests/natif/gpu-rust
apk add --quiet --root /nova/build/ports/webroot --initdb \
    --keys-dir /etc/apk/keys --repositories-file /etc/apk/repositories \
    --no-scripts $PACKAGES >/dev/null 2>&1 || true
test -e /nova/build/ports/webroot/lib/ld-musl-x86_64.so.1
# The ALSA plugin that plays into Nova's mixer (/dev/nova-audio), when
# alsa-lib is in the image (the browser's packages bring it).
if [ -e /nova/build/ports/webroot/usr/lib/libasound.so.2 ]; then
    mkdir -p /nova/build/ports/webroot/usr/lib/alsa-lib
    gcc -shared -fPIC -DPIC -O2 -Wall -o /nova/build/ports/webroot/usr/lib/alsa-lib/libasound_module_pcm_nova.so \
        /nova/tools/ports/alsa-nova/pcm_nova.c -lasound
    gcc -O2 -o /nova/build/ports/webroot/nova-tests/alsa /nova/tools/ports/tests/alsa.c -lasound -lm
fi
# The links busybox's install script would create (--no-scripts skips it).
if [ -x /nova/build/ports/webroot/bin/busybox ]; then
    for applet in \$(/nova/build/ports/webroot/bin/busybox --list-full); do
        [ -e /nova/build/ports/webroot/\$applet ] || ln -s /bin/busybox /nova/build/ports/webroot/\$applet
    done
fi
"

# The Web Browser fork, when built (ports/web-browser/build.sh): its
# package unpacked where Alpine would put it. The firefox-esr package
# stays for its dependencies; its own directory is dropped.
BROWSER_TARBALL=$(ls "$REPO"/build/ports/alpine/home/build/firefox-*/obj/dist/web-browser-*.tar.xz 2>/dev/null | head -1)
if [ -n "$BROWSER_TARBALL" ]; then
    mkdir -p "$STAGE/usr/lib"
    tar -xJf "$BROWSER_TARBALL" -C "$STAGE/usr/lib"
    rm -rf "$STAGE/usr/lib/firefox-esr"
    echo "[..] Web Browser : $(basename "$BROWSER_TARBALL")"
    # French interface: Mozilla's language pack of the same version,
    # installed into the profile at first start (distribution/extensions).
    if [ -f "$REPO/build/ports/fr.xpi" ]; then
        mkdir -p "$STAGE/usr/lib/web-browser/distribution/extensions"
        # Rebranded: the pack's own brand strings would say "Firefox".
        python3 "$REPO/tools/ports/rebrand-langpack.py" "$REPO/build/ports/fr.xpi" \
            "$STAGE/usr/lib/web-browser/distribution/extensions/langpack-fr@firefox.mozilla.org.xpi"
    fi
fi

# Phase 12: the browser and a test program as linked images (spec 3.5),
# the Nova binaries the kernel starts through the Nova C library.
if [ -x "$STAGE/usr/lib/web-browser/web-browser" ]; then
    python3 "$REPO/tools/nova-wrap.py" "$STAGE/usr/lib/web-browser/web-browser" \
        "$STAGE/usr/lib/web-browser/web-browser.cus" --app-id os.nova.web-browser --name "Web Browser" \
        --author "Nova OS" --group apps --version 140.12.0.0 --flags GUI,NETWORK,DEFAULT_CAPABLE \
        --permissions NETWORK_INTERNET,NETWORK_LOCAL,AUDIO_OUTPUT,FS_USER_HOME,CLIPBOARD,FULLSCREEN,NOTIFICATIONS
fi
python3 "$REPO/tools/nova-wrap.py" "$STAGE/nova-tests/natif/hello" "$STAGE/nova-tests/natif/hello.cus" \
    --app-id os.nova.essai.hello --name "Essai hello" --flags ""

# Files of Nova's own: the startup script and the browser's test prefs.
cp -r "$REPO/tools/ports/overlay/." "$STAGE/"
# Test clips of the video page (nova/video.html), made by ffmpeg on the
# host when it is there: a pattern with a frame counter and a 440 Hz tone.
if command -v ffmpeg >/dev/null && [ -d "$STAGE/usr/lib/web-browser/nova" ]; then
    for clip in essai.webm essai720.webm essai1080.webm essai.mp4; do
        [ -f "$REPO/build/ports/media/$clip" ] || case $clip in
            essai1080.webm) ffmpeg -hide_banner -loglevel error -y -f lavfi -i testsrc2=size=1920x1080:rate=30:duration=10 \
                        -f lavfi -i sine=frequency=440:duration=10 -c:v libvpx-vp9 -b:v 4M -deadline realtime \
                        -cpu-used 8 -row-mt 1 -c:a libopus -b:a 96k -shortest "$REPO/build/ports/media/$clip" ;;
            essai720.webm) ffmpeg -hide_banner -loglevel error -y -f lavfi -i testsrc2=size=1280x720:rate=30:duration=10 \
                        -f lavfi -i sine=frequency=440:duration=10 -c:v libvpx-vp9 -b:v 2M -deadline realtime \
                        -cpu-used 8 -c:a libopus -b:a 96k -shortest "$REPO/build/ports/media/$clip" ;;
            *.webm) ffmpeg -hide_banner -loglevel error -y -f lavfi -i testsrc2=size=854x480:rate=30:duration=10 \
                        -f lavfi -i sine=frequency=440:duration=10 -c:v libvpx-vp9 -b:v 1M -deadline realtime \
                        -cpu-used 8 -c:a libopus -b:a 96k -shortest "$REPO/build/ports/media/$clip" ;;
            *.mp4) ffmpeg -hide_banner -loglevel error -y -f lavfi -i testsrc2=size=854x480:rate=30:duration=10 \
                        -f lavfi -i sine=frequency=440:duration=10 -c:v libx264 -preset veryfast -b:v 1M \
                        -pix_fmt yuv420p -c:a aac -b:a 96k -shortest -movflags +faststart "$REPO/build/ports/media/$clip" ;;
        esac
        cp "$REPO/build/ports/media/$clip" "$STAGE/usr/lib/web-browser/nova/"
    done
fi

# The profile every session starts from, made here by the browser itself:
# started once on the host, in this very root (bubblewrap), it does its
# first-run work -- databases, the language pack, the startup cache --
# and quits (nova.cfg, NOVA_PREPARE_PROFILE). At every Nova session that
# work cost about a second of the browser's start. What belongs to one
# session (lock, session store, telemetry, caches of pages) is left out.
if [ -x "$STAGE/usr/lib/web-browser/web-browser" ] && command -v bwrap >/dev/null; then
    HOMEDIR="$REPO/build/ports/profile-home"
    rm -rf "$HOMEDIR"
    mkdir -p "$HOMEDIR/profile/chrome"
    cp "$STAGE/usr/lib/web-browser/nova/chrome/userChrome.css" "$HOMEDIR/profile/chrome/"
    if timeout 120 bwrap --bind "$STAGE" / --dev /dev --proc /proc --tmpfs /tmp \
        --bind "$HOMEDIR" /home/nova --unshare-user --uid 0 --gid 0 --unshare-net \
        --setenv HOME /home/nova --setenv PATH /usr/bin:/bin --setenv MOZ_HEADLESS 1 \
        --setenv NOVA_PREPARE_PROFILE 1 --setenv MOZ_CRASHREPORTER_DISABLE 1 \
        --setenv MOZ_DISABLE_CONTENT_SANDBOX 1 \
        /usr/lib/web-browser/web-browser --headless --no-remote --profile /home/nova/profile \
        >"$HOMEDIR.log" 2>&1 && [ -d "$HOMEDIR/profile/startupCache" ]; then
        (cd "$HOMEDIR/profile" && rm -rf lock .parentlock sessionstore.jsonlz4 sessionstore-backups \
            sessionCheckpoints.json Telemetry.ShutdownTime.txt datareporting cache2 thumbnails \
            safebrowsing times.json)
        rm -rf "$STAGE/home/nova"
        mkdir -p "$STAGE/usr/lib/web-browser/nova"
        rm -rf "$STAGE/usr/lib/web-browser/nova/profile"
        mv "$HOMEDIR/profile" "$STAGE/usr/lib/web-browser/nova/profile"
        echo "[..] profil prepare : $(du -sh "$STAGE/usr/lib/web-browser/nova/profile" | cut -f1)"
    else
        echo "[!!] profil non prepare (voir $HOMEDIR.log) : premier demarrage complet a chaque session"
        rm -rf "$STAGE/home/nova"
    fi
fi

# A test image opens the browser at login (tools/ports/test-window.sh).
if [ "$NOVA_AUTOSTART_BROWSER" = 1 ]; then
    touch "$STAGE/nova/open-browser-at-login"
fi

# Generated at boot by Nova, not taken from the host.
rm -f "$STAGE/etc/resolv.conf"

echo "[ok] racine du sous-systeme Linux prete : $STAGE"
echo "     a ecrire dans le volume Nova : tools/nova-fs.py import <disque> $STAGE /apps/web-browser/root"
